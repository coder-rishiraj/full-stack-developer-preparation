/**
 * Validates every Markdown lesson, then regenerates:
 *   - src/content/lessons/manifest.json  (lesson metadata the UI reads eagerly)
 *   - docs/CURRICULUM_CHECKLIST.md        (completed vs pending topics, per module)
 *
 * Run: npm run lessons:sync        (exit code 1 if any lesson has errors)
 */
import { createServer } from 'vite'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const lessonDir = path.join(root, 'src/content/lessons')

const server = await createServer({ root, server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' })

let failed = 0
try {
  const { TOPICS, TRACKS, SECTIONS, getTopicMeta } = await server.ssrLoadModule('/src/content/taxonomy.ts')
  const { checkLesson } = await server.ssrLoadModule('/src/content/lessons/validate.ts')
  const topicsMod = await server.ssrLoadModule('/src/content/topics/index.ts')

  const files = readdirSync(lessonDir).filter((f) => f.endsWith('.md')).sort()
  const ids = new Set(files.map((f) => f.slice(0, -3)))
  const ctx = {
    getTopic: getTopicMeta,
    childrenOf: (id) => TOPICS.filter((t) => t.parentTopicId === id),
    hasOwnLesson: (id) => ids.has(id),
  }

  const manifest = {}
  const conceptHome = {}
  for (const file of files) {
    const id = file.slice(0, -3)
    const res = checkLesson(id, readFileSync(path.join(lessonDir, file), 'utf8'), ctx)
    if (res.errors.length) {
      failed++
      console.error(`✗ ${file}\n    ${res.errors.join('\n    ')}`)
    }
    const fm = res.parsed.frontmatter
    manifest[id] = {
      title: fm.title,
      summary: fm.summary,
      difficulty: fm.difficulty,
      minutes: fm.minutes,
      words: res.parsed.wordCount,
      concepts: res.concepts,
    }
    for (const c of res.concepts) conceptHome[c] ??= id
  }
  writeFileSync(path.join(lessonDir, 'manifest.json'), JSON.stringify(manifest, null, 1) + '\n')

  // Checklist
  const generatedIds = new Set()
  for (const id of topicsMod.getReadyTopicIds()) {
    const c = await topicsMod.loadTopicContent(id)
    if (c?.generated) generatedIds.add(id)
  }
  const statusOf = (t) => {
    if (ids.has(t.id)) return 'lesson'
    if (conceptHome[t.id]) return 'section'
    if (!topicsMod.hasTopicContent(t.id)) return 'missing'
    return generatedIds.has(t.id) ? 'template' : 'notes'
  }
  const MARK = { lesson: '✅ lesson', section: '✅ in parent lesson', notes: '◐ condensed notes', template: '○ template only', missing: '✗ no content' }

  const totals = { all: 0, done: 0 }
  const trackRows = []
  let body = ''
  for (const track of TRACKS) {
    const sections = SECTIONS.filter((s) => s.track === track.id).sort((a, b) => a.order - b.order)
    let tAll = 0
    let tDone = 0
    let tBody = ''
    for (const s of sections) {
      const items = TOPICS.filter((t) => t.sectionId === s.id && t.curriculumLevel === 'classified-item')
      if (!items.length) continue
      const done = items.filter((t) => ids.has(t.id)).length
      tAll += items.length
      tDone += done
      tBody += `\n#### ${s.id} · ${s.title} — ${done}/${items.length}\n\n`
      for (const t of items) {
        const kids = TOPICS.filter((k) => k.parentTopicId === t.id)
        const kidsDone = kids.filter((k) => statusOf(k).startsWith('l') || statusOf(k) === 'section').length
        const st = statusOf(t)
        const words = manifest[t.id]?.words
        tBody += `- [${st === 'lesson' ? 'x' : ' '}] \`${t.id}\` ${t.title} — ${MARK[st]}${words ? ` (${words} words)` : ''}${kids.length ? ` · nested ${kidsDone}/${kids.length}` : ''}\n`
      }
    }
    totals.all += tAll
    totals.done += tDone
    trackRows.push(`| ${track.id} | ${track.name} | ${tDone} / ${tAll} | ${tAll ? Math.round((tDone / tAll) * 100) : 0}% |`)
    body += `\n### Track ${track.id} — ${track.name}\n${tBody}`
  }

  const md = `# Curriculum lesson checklist

Generated by \`npm run lessons:sync\` — do not edit by hand. The curriculum inventory is
[CONTENTS.md](../CONTENTS.md); lesson standards are in [LESSON_GUIDE.md](LESSON_GUIDE.md).

A topic counts as done only when it has a full Markdown lesson that passes validation
(\`src/content/lessons/<id>.md\`). Nested concepts are done when their parent lesson teaches
them under an anchored heading.

| Track | Name | Lessons | Done |
|---|---|---|---|
${trackRows.join('\n')}
| | **All tracks** | **${totals.done} / ${totals.all}** | **${totals.all ? Math.round((totals.done / totals.all) * 100) : 0}%** |

Legend: ✅ lesson written · ◐ condensed notes only · ○ generic template only · ✗ no content
${body}`
  writeFileSync(path.join(root, 'docs/CURRICULUM_CHECKLIST.md'), md)
  console.log(`${files.length} lessons, ${failed} with errors. Classified topics with lessons: ${totals.done}/${totals.all}`)
} finally {
  await server.close()
}
process.exit(failed ? 1 : 0)
